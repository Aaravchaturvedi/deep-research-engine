// NOTE: html2pdf.js is lazy-loaded inside downloadPdf so the PDF stack
// stays out of the initial bundle.

function slugify(s: string): string {
  return (
    s
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 50) || "report"
  );
}

